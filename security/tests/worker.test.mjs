// Тест сервера: подпись Telegram и пропуск Firebase. Запуск: node security/tests/worker.test.mjs
import crypto from "node:crypto";
import { verifyInitData, firebaseCustomToken } from "../worker/src/index.js";
import worker from "../worker/src/index.js";
const BOT = "123456789:TEST_TOKEN_abcdefghijklmnopqrstuvwxyz12";
const sign = (fields) => { const check = Object.entries(fields).map(([k, v]) => `${k}=${v}`).sort().join("\n");
  const secret = crypto.createHmac("sha256", "WebAppData").update(BOT).digest();
  const hash = crypto.createHmac("sha256", secret).update(check).digest("hex");
  return new URLSearchParams({ ...fields, hash }).toString(); };
let fail = 0; const ok = (c, m) => { console.log((c ? "PASS " : "FAIL ") + m); if (!c) fail++; };
const now = Date.now(), user = JSON.stringify({ id: 1661222371, first_name: "Artem", username: "ramen1n0" });
const good = sign({ auth_date: String(Math.floor(now / 1000) - 60), query_id: "AAH", user });
ok((await verifyInitData(good, BOT))?.id === "1661222371", "верная подпись принимается");
ok(!(await verifyInitData(good.replace("Artem", "Hacker"), BOT)), "изменённые данные отклоняются");
ok(!(await verifyInitData(good, "999:OTHER")), "чужой токен бота отклоняется");
ok(!(await verifyInitData(sign({ auth_date: String(Math.floor(now / 1000) - 90000), user }), BOT)), "старая подпись (>24ч) отклоняется");
ok(!(await verifyInitData("user=%7B%22id%22%3A1%7D&hash=" + "0".repeat(64), BOT)), "подделанный hash отклоняется");
const { privateKey, publicKey } = crypto.generateKeyPairSync("rsa", { modulusLength: 2048 });
const sa = { client_email: "firebase-adminsdk-x@island-6cbab.iam.gserviceaccount.com", private_key: privateKey.export({ type: "pkcs8", format: "pem" }) };
const tok = await firebaseCustomToken(sa, "utg1661222371", { admin: true });
const [h, b, s] = tok.split(".");
ok(crypto.verify("RSA-SHA256", Buffer.from(h + "." + b), publicKey, Buffer.from(s, "base64url")), "пропуск подписан ключом сервисного аккаунта");
const pl = JSON.parse(Buffer.from(b, "base64url"));
ok(pl.uid === "utg1661222371" && pl.claims.admin === true && pl.aud.includes("identitytoolkit") && pl.exp - pl.iat === 3600, "в пропуске uid, admin и срок 1 час");
const env = { TELEGRAM_TOKEN: BOT, FIREBASE_SA: JSON.stringify(sa), ADMIN_IDS: "1661222371", ALLOWED_ORIGINS: "https://artemionov123.github.io" };
const call = async (body) => worker.fetch(new Request("https://x.workers.dev/auth", { method: "POST", body, headers: { Origin: "https://artemionov123.github.io" } }), env);
let r = await call(good); let j = await r.json();
ok(r.status === 200 && j.admin === true && j.uid === "utg1661222371" && r.headers.get("Access-Control-Allow-Origin") === "https://artemionov123.github.io", "/auth: админ получает пропуск");
const other = sign({ auth_date: String(Math.floor(now / 1000)), user: JSON.stringify({ id: 777001, first_name: "Petya" }) });
r = await call(other); j = await r.json();
ok(r.status === 200 && j.admin === false && !JSON.parse(Buffer.from(j.token.split(".")[1], "base64url")).claims.admin, "/auth: обычный игрок без admin");
r = await call("hash=bad"); ok(r.status === 401, "/auth: без подписи — 401");
r = await worker.fetch(new Request("https://x.workers.dev/setup?key=wrong"), env); ok(r.status === 403, "/setup без ключа — 403");
r = await worker.fetch(new Request("https://x.workers.dev/bot", { method: "POST", body: "{}" }), env); ok(r.status === 403, "/bot без секрета Telegram — 403");
console.log(fail ? `\n${fail} FAILED` : "\nALL PASSED"); process.exit(fail ? 1 : 0);
